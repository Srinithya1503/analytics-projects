-- =====================================================================
-- HospSafe-Analytics: CMS Patient Safety & Quality Performance Tracker
-- schema.sql
--
-- Purpose:
--   Builds a two-table relational schema in MySQL that models the
--   structure of the publicly available CMS "Hospital General
--   Information" dataset (data.cms.gov), plus a companion table of
--   patient-safety-group quality measure counts modeled after CMS's
--   Timely & Effective Care / Patient Safety measure group summaries.
--
-- Engine: MySQL 8.0+
-- =====================================================================

DROP DATABASE IF EXISTS hospsafe_analytics;
CREATE DATABASE hospsafe_analytics;
USE hospsafe_analytics;

-- ---------------------------------------------------------------------
-- Table: hospitals
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS safety_metrics;
DROP TABLE IF EXISTS hospitals;

CREATE TABLE hospitals (
    facility_id         VARCHAR(10)     NOT NULL,
    facility_name       VARCHAR(150)    NOT NULL,
    state               CHAR(2)         NOT NULL,
    hospital_type       VARCHAR(60)     NOT NULL,
    hospital_ownership  VARCHAR(60)     NOT NULL,
    overall_rating      INT             NULL,  -- 1-5 stars; NULL = "Not Available" in CMS source
    PRIMARY KEY (facility_id),
    CONSTRAINT chk_overall_rating CHECK (overall_rating IS NULL OR overall_rating BETWEEN 1 AND 5)
) ENGINE=InnoDB;

CREATE INDEX idx_hospitals_state ON hospitals (state);
CREATE INDEX idx_hospitals_ownership ON hospitals (hospital_ownership);

-- ---------------------------------------------------------------------
-- Table: safety_metrics
-- Mirrors CMS "Patient Safety" measure-group summary fields
-- (safety group measure counts, and comparative better/worse/no-different
-- counts against the national rate), plus a readmission "worse" count
-- pulled from the companion CMS "Readmissions" measure group.
-- ---------------------------------------------------------------------
CREATE TABLE safety_metrics (
    metric_id                   INT AUTO_INCREMENT,
    facility_id                 VARCHAR(10)  NOT NULL,
    safety_group_measure_count  INT          NOT NULL DEFAULT 0,
    safety_measures_better      INT          NOT NULL DEFAULT 0,
    safety_measures_no_different INT         NOT NULL DEFAULT 0,
    safety_measures_worse       INT          NOT NULL DEFAULT 0,
    readm_measures_worse        INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (metric_id),
    CONSTRAINT fk_safety_metrics_facility
        FOREIGN KEY (facility_id) REFERENCES hospitals (facility_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
) ENGINE=InnoDB;

CREATE INDEX idx_safety_metrics_facility ON safety_metrics (facility_id);

